/**
 * check-doc-constants — the SEMANTIC CONSTANTS in prose must match the code.
 *
 * Why this guard exists
 * ---------------------
 * `check-doc-consistency.mjs` anchors test-suite counts (how many assertions a
 * suite runs). The 2026-09-11 review pointed out that the more valuable anchors
 * are the *semantic constants* — how many note tools exist, how many papers the
 * literature library holds — because those are stated in prose, drift silently,
 * and mislead a reader who has no way to check. It found "同一事实五个数字" for
 * the paper count and a wrong tool count in the READMEs.
 *
 * What is checked here
 * --------------------
 * 1. **note-tool count** — derived from the `name: "note_*"` registrations in
 *    `dsh/preset/note-tools.mjs`, compared against the number each doc states.
 * 2. **literature count** — derived from the directories actually present under
 *    `literature/.raw/`, compared against `docs/literature.md`. The raw corpus
 *    is gitignored (regenerated by `lit-import.mjs`), so this check **SKIPs**
 *    when `.raw` is absent — a local-only anchor, reported as such rather than
 *    passing quietly.
 *
 * A doc that stops matching the expected phrasing FAILS rather than being
 * skipped: silently matching nothing is how an anchor rots into decoration.
 */
import { readdirSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
let failed = 0;
const fail = (msg) => { console.log(`[FAIL] ${msg}`); failed += 1; };

// ── derived truth: how many note tools exist ────────────────────────────────
const noteToolsSrc = readFileSync(join(root, "dsh", "preset", "note-tools.mjs"), "utf8");
const toolNames = [...noteToolsSrc.matchAll(/name:\s*["'](note_[a-z_]+)["']/g)].map((m) => m[1]);
if (toolNames.length === 0) {
  fail("found 0 `name: \"note_*\"` registrations in dsh/preset/note-tools.mjs — the extractor is broken");
}

// Numerals that actually appear in this repo's docs. Deliberately small: an
// unparseable claim must fail loudly, not be ignored.
const NUMERALS = new Map([
  ["one", 1], ["two", 2], ["three", 3], ["four", 4], ["five", 5], ["six", 6], ["seven", 7], ["eight", 8],
  ["一", 1], ["二", 2], ["两", 2], ["三", 3], ["四", 4], ["五", 5], ["六", 6], ["七", 7], ["八", 8]
]);
const toNumber = (token) => {
  if (/^\d+$/.test(token)) return Number(token);
  return NUMERALS.get(token.toLowerCase()) ?? null;
};

// Claim sites. Each must state the count of note tools somewhere on the matched
// line; the pattern captures the numeral immediately preceding the noun.
const CLAIM_SITES = [
  ["README.md", /([A-Za-z]+)\s+note tools/i],
  ["README.zh.md", /([一二三四五六七八九十]+)个笔记工具/],
  ["docs/memory/design.md", /([一二三四五六七八九十]+)个笔记工具/]
];
for (const [rel, pattern] of CLAIM_SITES) {
  const text = readFileSync(join(root, rel), "utf8");
  const m = pattern.exec(text);
  if (m === null) {
    fail(`${rel}: no note-tool count matching ${pattern} — the wording changed, so update this guard rather than losing the anchor`);
    continue;
  }
  const claimed = toNumber(m[1]);
  if (claimed === null) {
    fail(`${rel}: cannot parse "${m[1]}" as a number (add it to NUMERALS)`);
  } else if (claimed !== toolNames.length) {
    fail(`${rel} claims ${claimed} note tools, but dsh/preset/note-tools.mjs registers ${toolNames.length} (${toolNames.join(", ")})`);
  }
}

// ── literature count: local-only (the raw corpus is gitignored) ─────────────
const rawDir = join(root, "..", "literature", ".raw");
const repoRaw = join(root, "literature", ".raw");
const raw = existsSync(repoRaw) ? repoRaw : (existsSync(rawDir) ? rawDir : null);
if (raw === null) {
  console.log("SKIP  literature count: literature/.raw is absent (gitignored corpus — regenerate with scripts/lit-import.mjs)");
} else {
  const dirs = readdirSync(raw, { withFileTypes: true }).filter((e) => e.isDirectory()).length;
  const lit = readFileSync(join(root, "docs", "literature.md"), "utf8");
  const m = /\*\*(\d+)\*\*\s*条 BibTeX/.exec(lit) ?? /(\d+)\s*篇/.exec(lit);
  if (m === null) {
    fail("docs/literature.md: no paper count found (expected `**N** 条 BibTeX` or `N 篇`)");
  } else if (Number(m[1]) !== dirs) {
    fail(`docs/literature.md claims ${m[1]} papers, but literature/.raw holds ${dirs} directories`);
  } else {
    console.log(`literature count: ${dirs} (matches docs/literature.md)`);
  }
}

// ── the two changelogs must stay two DIFFERENT things ───────────────────────
// `CHANGELOG.md`       = per-version release summary (what a USER gets).
// `docs/changelog.md`  = the maintenance ledger (WHY it changed, how it was
//                        found, what went wrong).
//
// They overlap in SUBJECT by design — two layers, as the maintenance guide
// prescribes — but never in STRUCTURE. The rot to prevent is the ledger growing
// per-version headings and quietly becoming a second release changelog, which
// would bury the "why" it exists for. Both files must also point at each other:
// a reader who finds only one layer never learns the other exists.
{
  const releaseNotes = readFileSync(join(root, "CHANGELOG.md"), "utf8");
  const ledger = readFileSync(join(root, "docs", "changelog.md"), "utf8");
  const versionHeading = /^## \[\d+\.\d+\.\d+\]/m.exec(ledger);
  if (versionHeading !== null) {
    fail(`docs/changelog.md has a version heading (${versionHeading[0]}) — release notes belong in CHANGELOG.md; the ledger is organised by dated topic`);
  }
  if (!/docs\/changelog\.md/.test(releaseNotes)) {
    fail("CHANGELOG.md must point at docs/changelog.md for the why — otherwise a reader of the release summary never learns the ledger exists");
  }
  if (!/CHANGELOG\.md/.test(ledger)) {
    fail("docs/changelog.md must point at CHANGELOG.md for the release summary");
  }
}

if (failed > 0) {
  console.log(`\n${failed} semantic-constant mismatch(es). Prose numbers must come from the code, not from memory.`);
  process.exit(1);
}
console.log(`doc-constants: ok (${toolNames.length} note tools ${toolNames.join("/")}; every claim site agrees)`);
